test("response playback pauses, resumes, replays and resets when changing examples", async ({ page }) => {
  await page.goto(opus)
  const responses = page.locator(".evidence-response")
  await responses.scrollIntoViewIfNeeded()
  const visual = responses.locator(".evidence-response__visual").first()
  await expect(visual).toBeEmpty()
  await responses.getByRole("button", { name: "Play", exact: true }).click()
  await expect(visual).not.toBeEmpty()
  await responses.getByRole("button", { name: "Pause", exact: true }).click()
  await expect(responses.getByRole("status")).toHaveText("Paused")
  const paused = await visual.textContent()
  await page.waitForTimeout(150)
  expect(await visual.textContent()).toBe(paused)
  await responses.getByRole("button", { name: "Resume", exact: true }).click()
  await expect(responses.getByRole("status")).toHaveText("Playing")
  await responses.getByRole("tab", { name: "Summarizing a thread" }).click()
  await expect(responses.getByRole("status")).toHaveText("Ready")
  await expect(responses.locator(".evidence-response__visual").first()).toBeEmpty()
  await responses.getByRole("button", { name: "Replay both responses" }).click()
  await expect(responses.getByRole("status")).toHaveText("Playing")
})

test("mobile table scrolls with pinned labels and subject without overflowing the page", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(opus)
  const viewport = page.locator(".evidence-benchmark .evidence-comparison-viewport")
  await viewport.scrollIntoViewIfNeeded()
  await expect(viewport).toHaveAttribute("data-overflow", "true")
  const pinned = viewport.locator("thead .evidence-comparison-highlight")
  const original = await pinned.boundingBox()
  await viewport.evaluate(element => { element.scrollLeft = 250 })
  await expect.poll(async () => (await pinned.boundingBox())?.x).toBe(original?.x)
  await viewport.evaluate(element => { element.scrollLeft = element.scrollWidth })
  const lastColumn = await viewport.locator("thead th").last().boundingBox()
  const region = await viewport.boundingBox()
  expect(lastColumn!.x).toBeGreaterThanOrEqual(original!.x + original!.width - 1)
  expect(lastColumn!.x + lastColumn!.width).toBeLessThanOrEqual(region!.x + region!.width + 1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.getByRole("button", { name: "Open navigation" }).click()
  await expect(page.getByRole("dialog")).toBeVisible()
  await page.keyboard.press("Escape")
  await expect(page.getByRole("dialog")).toHaveCount(0)
})

