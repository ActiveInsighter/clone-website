import { expect, test, type Page } from "@playwright/test"

const opus = "/clones/anthropic/claude-opus-5-5"

async function settleHero(page: Page) {
  await page.evaluate(() => window.scrollTo({ top: 100, behavior: "instant" }))
  await expect(page.locator(".opus-hero")).toHaveAttribute("data-phase", "settled")
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: "instant" }))
  await expect.poll(() => page.evaluate(() => scrollY)).toBe(0)
}

test("source page renders real data and independently interactive chart instances", async ({ page }) => {
  const errors: string[] = []
  page.on("pageerror", error => errors.push(error.message))
  await page.goto(opus)
  await settleHero(page)
  await page.getByRole("button", { name: "Research", exact: true }).click()
  await expect(page.getByRole("menuitem", { name: "Alignment", exact: true })).toHaveAttribute("href", "https://www.anthropic.com/research/team/alignment")
  await page.keyboard.press("Escape")
  await expect(page.getByRole("menu")).toHaveCount(0)
  await expect(page.getByRole("heading", { name: "Claude Opus 5.5", exact: true })).toHaveCount(1)
  await expect(page.locator(".evidence-benchmark tbody tr")).toHaveCount(9)
  const charts = page.locator(".opus-charts").first()
  const panel = charts.getByRole("tabpanel")
  await panel.scrollIntoViewIfNeeded()
  await expect(panel.locator(".evidence-chart-point circle")).toHaveCount(25)
  const legend = panel.getByRole("button", { name: "Opus 5.5", exact: true })
  await legend.click()
  await expect(legend).toHaveAttribute("aria-pressed", "false")
  await expect(panel.locator(".evidence-chart-point circle")).toHaveCount(20)
  await legend.click()
  await expect(panel.locator(".evidence-chart-point circle")).toHaveCount(25)
  await panel.getByRole("button", { name: "View chart data" }).click()
  await expect(panel.locator(".evidence-chart-data tbody tr")).toHaveCount(25)
  const chartTabs = charts.getByRole("tab")
  await chartTabs.first().focus()
  await page.keyboard.press("ArrowRight")
  await expect(chartTabs.nth(1)).toHaveAttribute("aria-selected", "true")
  const ids = await page.locator("[data-chart]").evaluateAll(nodes => nodes.map(node => node.getAttribute("data-chart")))
  expect(new Set(ids).size).toBe(ids.length)
  expect(errors).toEqual([])
})

